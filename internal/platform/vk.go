package platform

var vkSpecial = map[byte]uint16{0x28: 0x0D, 0x29: 0x1B, 0x2A: 0x08, 0x2B: 0x09, 0x2C: 0x20, 0x39: 0x14, 0x46: 0x2C, 0x47: 0x91, 0x48: 0x13,
	0x49: 0x2D, 0x4A: 0x24, 0x4B: 0x21, 0x4C: 0x2E, 0x4D: 0x23, 0x4E: 0x22, 0x4F: 0x27, 0x50: 0x25, 0x51: 0x28, 0x52: 0x26, 0x53: 0x90,
	0x2D: 0xBD, 0x2E: 0xBB, 0x2F: 0xDB, 0x30: 0xDD, 0x31: 0xDC, 0x33: 0xBA, 0x34: 0xDE, 0x35: 0xC0, 0x36: 0xBC, 0x37: 0xBE, 0x38: 0xBF, 0x64: 0xE2}

func vkOf(u byte) uint16 {
	switch {
	case u >= 0x04 && u <= 0x1D:
		return uint16('A' + u - 0x04)
	case u >= 0x1E && u <= 0x26:
		return uint16('1' + u - 0x1E)
	case u == 0x27:
		return '0'
	case u >= 0x3A && u <= 0x45:
		return uint16(0x70 + u - 0x3A)
	case u >= 0x68 && u <= 0x73:
		return uint16(0x7C + u - 0x68)
	}
	return vkSpecial[u]
}
