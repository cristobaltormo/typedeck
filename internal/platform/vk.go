func vkOf(u byte) uint16 {
	switch {
	case u >= 0x04 && u <= 0x1D:
		return uint16('A' + u - 0x04)
	case u >= 0x1E && u <= 0x26:
		return uint16('1' + u - 0x1E)
	case u == 0x27:
		return '0'
	case u >= 0x3A && u <= 0x45:
		return uint16(0x70 + u - 0x3A)
	case u >= 0x59 && u <= 0x61:
		return uint16(0x61 + u - 0x59)
	case u >= 0x68 && u <= 0x73:
		return uint16(0x7C + u - 0x68)
	}
	return vkSpecial[u]
}

func isExtendedVK(vk uint16) bool {
	switch {
	case vk&vkExtended != 0:
		return true
	case vk >= 0x21 && vk <= 0x28, vk >= 0xA6 && vk <= 0xB7:
		return true
	}
	switch vk {
	case 0x03, 0x2C, 0x2D, 0x2E, 0x5B, 0x5C, 0x5D, 0x6F, 0x90, 0xA3, 0xA5:
		return true
	}
	return false
}
