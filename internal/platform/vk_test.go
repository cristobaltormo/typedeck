package platform

import "testing"

func TestVirtualKeys(t *testing.T) {
	cases := map[byte]uint16{0x04: 'A', 0x1D: 'Z', 0x1E: '1', 0x27: '0', 0x3A: 0x70, 0x45: 0x7B, 0x68: 0x7C, 0x28: 0x0D, 0x29: 0x1B, 0x2C: 0x20, 0x4F: 0x27, 0x52: 0x26,
		0x54: 0x6F, 0x55: 0x6A, 0x56: 0x6D, 0x57: 0x6B, 0x58: 0x0D | vkExtended, 0x59: 0x61, 0x61: 0x69, 0x62: 0x60, 0x63: 0x6E,
		0x32: 0xDC, 0x64: 0xE2, 0x65: 0x5D, 0xE0: 0xA2, 0xE6: 0xA5, 0xE3: 0x5B}
	for u, want := range cases {
		if got := vkOf(u); got != want {
			t.Errorf("usage %02X -> %02X, expected %02X", u, got, want)
		}
	}
	if vkOf(0xFF) != 0 {
		t.Error("an unknown usage must give no key")
	}
}

func TestExtendedKeys(t *testing.T) {
	for _, vk := range []uint16{0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27, 0x28, 0x2C, 0x2D, 0x2E, 0x5B, 0x5C, 0x5D, 0x6F, 0x90, 0xA3, 0xA5, 0xAD, 0xB3, 0x0D | vkExtended} {
		if !isExtendedVK(vk) {
			t.Errorf("%02X must be sent with the extended flag", vk)
		}
	}
	for _, vk := range []uint16{'A', '1', 0x0D, 0x20, 0x70, 0x6A, 0x60, 0xA0, 0xA2} {
		if isExtendedVK(vk) {
			t.Errorf("%02X must not be extended", vk)
		}
	}
}
