pub const VK_EXTENDED: u16 = 0x100;

pub fn vk_of(u: u8) -> u16 {
    let u16v = u16::from(u);
    match u {
        0x04..=0x1D => u16::from(b'A') + u16v - 0x04,
        0x1E..=0x26 => u16::from(b'1') + u16v - 0x1E,
        0x27 => u16::from(b'0'),
        0x3A..=0x45 => 0x70 + u16v - 0x3A,
        0x59..=0x61 => 0x61 + u16v - 0x59,
        0x68..=0x73 => 0x7C + u16v - 0x68,
        _ => match u {
            0x28 => 0x0D,
            0x29 => 0x1B,
            0x2A => 0x08,
            0x2B => 0x09,
            0x2C => 0x20,
            0x39 => 0x14,
            0x46 => 0x2C,
            0x47 => 0x91,
            0x48 => 0x13,
            0x49 => 0x2D,
            0x4A => 0x24,
            0x4B => 0x21,
            0x4C => 0x2E,
            0x4D => 0x23,
            0x4E => 0x22,
            0x4F => 0x27,
            0x50 => 0x25,
            0x51 => 0x28,
            0x52 => 0x26,
            0x53 => 0x90,
            0x2D => 0xBD,
            0x2E => 0xBB,
            0x2F => 0xDB,
            0x30 => 0xDD,
            0x31 | 0x32 => 0xDC,
            0x33 => 0xBA,
            0x34 => 0xDE,
            0x35 => 0xC0,
            0x36 => 0xBC,
            0x37 => 0xBE,
            0x38 => 0xBF,
            0x54 => 0x6F,
            0x55 => 0x6A,
            0x56 => 0x6D,
            0x57 => 0x6B,
            0x58 => 0x0D | VK_EXTENDED,
            0x62 => 0x60,
            0x63 => 0x6E,
            0x67 => 0x92,
            0x64 => 0xE2,
            0x65 => 0x5D,
            0x85 => 0xC2,
            0x87 => 0xC1,
            0x88 | 0x90 => 0x15,
            0x8A => 0x1C,
            0x8B => 0x1D,
            0x91 => 0x19,
            0xE0 => 0xA2,
            0xE1 => 0xA0,
            0xE2 => 0xA4,
            0xE3 => 0x5B,
            0xE4 => 0xA3,
            0xE5 => 0xA1,
            0xE6 => 0xA5,
            0xE7 => 0x5C,
            _ => 0,
        },
    }
}

pub fn is_extended_vk(vk: u16) -> bool {
    vk & VK_EXTENDED != 0
        || (0x21..=0x28).contains(&vk)
        || (0xA6..=0xB7).contains(&vk)
        || matches!(vk, 0x03 | 0x2C | 0x2D | 0x2E | 0x5B | 0x5C | 0x5D | 0x6F | 0x90 | 0xA3 | 0xA5)
}
